function out = five_audit()
% Static topology audit of the four-group + COM five-electrode models.
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
dir5 = fullfile(root,'HRG_WA_simulink','piezo_v10','five_electrode_20261110');
addpath(dir5);
modes = {'continuous','tdm_shared'};
out = struct('generated',datestr(now,31),'modes',[]);
for j = 1:numel(modes)
    mode = modes{j};
    c = five_config(mode,0);
    H = c.portCoupling; D = c.portDriveMap; S = c.portSenseMap; C = c.portCapacitance_F;
    rec = struct('mode',mode, ...
        'group_angles_deg',c.groupAngles_deg.', ...
        'group_charge_gain',c.portOptions.group_charge_gain.', ...
        'group_capacitance_F',c.portShuntCapacitance_F.', ...
        'cds_F',c.p.Cds, ...
        'H',H,'drive_map',D,'sense_map',S, ...
        'rank_H',rank(H),'rank_drive',rank(H'*D),'rank_sense',rank(S*H), ...
        'cond_H',cond(H),'cond_drive',cond(H'*D),'cond_sense',cond(S*H), ...
        'cond_C',cond(C),'eig_C',eig(C).', ...
        'common_terminal',c.commonTerminal, ...
        'adc_bits',c.p.adc_bits,'dac_bits',c.p.dac_bits,'fs_Hz',1/c.Ts, ...
        'frame_rate_Hz',(1/c.Ts)/c.frame, ...
        'drive_pre',c.gain_check.drive_pre_V_per_V,'sense_pre',c.gain_check.sense_pre_V_per_V, ...
        'thx_cv_gain',c.p.thx_cv_gain);
    out.modes = [out.modes;rec];
    fprintf('AUDIT5 %-12s rank H/D/S=%d/%d/%d cond H/D/S=%.3g/%.3g/%.3g condC=%.3g caps=%s\n', ...
        mode,rec.rank_H,rec.rank_drive,rec.rank_sense,rec.cond_H,rec.cond_drive,rec.cond_sense,rec.cond_C,mat2str(rec.group_capacitance_F,4));
end
fid = fopen(fullfile(here,'five_audit.json'),'w','n','UTF-8');
assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(out,'PrettyPrint',true));
fclose(fid);
end
