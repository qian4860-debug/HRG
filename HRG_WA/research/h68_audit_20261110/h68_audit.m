function audit = h68_audit()
% Static audit of the 6800 Hz MATLAB configuration and native Simulink models.
% Does not run a closed-loop simulation; reads the committed model files and
% records which requested features are present.
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));              % ...\HRG_WA
modelDir = fullfile(root,'HRG_WA_simulink','piezo_v10','head6800_20261109');
addpath(modelDir);
modes = {'continuous','tdm_shared','tdm_separate'};
audit = struct('generated',datestr(now,31),'modes',[]);
for j = 1:numel(modes)
    mode = modes{j};
    c = h68_config(mode,0);
    m = ['hrg_6800_' mode];
    load_system(fullfile(modelDir,'models',[m '.slx']));
    cleanup = onCleanup(@() close_system(m,0));
    blocks = find_system(m,'LookUnderMasks','all','FollowLinks','on','Type','block');
    names = get_param(blocks,'Name');
    types = get_param(blocks,'BlockType');
    thx = sum(strcmp(names,'THX2024 matched CV gain'));
    badTypes = any(ismember(types,{'S-Function','MATLABFcn','InterpretedMATLABFcn','MATLABSystem','FromWorkspace'}));
    sf = find_system(m,'LookUnderMasks','all','SFBlockType','MATLAB Function');
    rec = struct('mode',mode,'head',c.head, ...
        'adc_bits',c.p.adc_bits,'dac_bits',c.p.dac_bits,'fs_Hz',1/c.Ts, ...
        'samples_per_carrier',c.n,'frame_samples',c.frame,'frame_rate_Hz',(1/c.Ts)/c.frame, ...
        'pre_gain',c.p.pre_gain,'power_gain',c.p.power_gain, ...
        'drive_pre',c.gain_check.drive_pre_V_per_V,'sense_pre',c.gain_check.sense_pre_V_per_V, ...
        'thx_cv_gain',c.p.thx_cv_gain,'thx_charge_per_input_C',c.p.thx_charge_per_input, ...
        'cv_mode',c.p.cv_mode,'blocks',numel(blocks),'thx_gain_blocks',thx, ...
        'has_runtime_matlab_block',badTypes || ~isempty(sf), ...
        'cds_F',c.p.Cds,'vmax_V',c.p.vmax,'electrode_limit_V',c.gain_check.electrode_limit_V, ...
        'temperature_model',c.head.temperature_model);
    audit.modes = [audit.modes;rec];
    fprintf('AUDIT %s blocks=%d thx=%d bad=%d fs=%.0f bits=%d/%d pre=%.3g thx=%.3g\n', ...
        mode,numel(blocks),thx,double(badTypes||~isempty(sf)),1/c.Ts,c.p.adc_bits,c.p.dac_bits,c.p.pre_gain,c.p.thx_cv_gain);
    clear cleanup
end
% Minimum rates under the stated assumptions.
f0 = 6800; df = 0.05; fhi = f0 + df/2;
audit.rates = struct( ...
    'carrier_only_strict_lower_Hz',2*fhi, ...
    'with_100Hz_envelope_strict_lower_Hz',2*(fhi+100), ...
    'ad9215_min_clock_Hz',5e6, ...
    'tdm_min_integer_samples_per_cycle',ceil(5e6/f0/4)*4, ...
    'tdm_min_clock_Hz',ceil(5e6/f0/4)*4*f0, ...
    'continuous_1us_settle_max_Hz',1/1e-6, ...
    'continuous_2us_settle_max_Hz',1/2e-6, ...
    'continuous_544k_samples_per_cycle',544e3/f0, ...
    'dac_8_samples_per_cycle_Hz',8*f0, ...
    'dac_16_samples_per_cycle_Hz',16*f0, ...
    'dac_32_samples_per_cycle_Hz',32*f0);
fid = fopen(fullfile(here,'audit.json'),'w','n','UTF-8');
assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(audit,'PrettyPrint',true));
fclose(fid);
fprintf('RATES nyq=%.3f with100=%.3f tdm_min=%.3f (n=%d) cont1us=%.3f cont2us=%.3f\n', ...
    audit.rates.carrier_only_strict_lower_Hz,audit.rates.with_100Hz_envelope_strict_lower_Hz, ...
    audit.rates.tdm_min_clock_Hz,audit.rates.tdm_min_integer_samples_per_cycle, ...
    audit.rates.continuous_1us_settle_max_Hz,audit.rates.continuous_2us_settle_max_Hz);
end
