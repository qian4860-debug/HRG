function dx = HRG_WA_fast_rhs(t, x, p, forceFcn)
% HRG_WA_FAST_RHS  Optional carrier-level 2-DOF resonator dynamics.
%
% 功能说明：
%   本函数提供一个可选的载波级二自由度谐振子动力学模型。
%   与 HRG_WA_rhs.m 的慢变量模型不同，本函数直接描述 x/y 两个正交检测轴上的
%   位移和速度，因此可以接入电极力模型、检测链路模型，并进行显式同步解调。
%
% 适用场景：
%   1. 需要仿真真实载波振动波形 X/Y 时；
%   2. 需要验证电极力分配、驱动电压、检测电容和同步解调算法时；
%   3. 需要与 Verilog/SystemVerilog 数字解调或控制模块联合验证时。
%
% 注意事项：
%   该模型含有谐振频率 p.f0 对应的高速载波。若 p.f0=5 kHz，仿真步长通常需要
%   远小于 1/p.f0，例如 1e-6 s 量级；因此运算量会明显大于慢变量模型。
%
% 状态向量：
%   x(1) = X      X 检测轴位移。
%   x(2) = Y      Y 检测轴位移。
%   x(3) = Xdot   X 检测轴速度。
%   x(4) = Ydot   Y 检测轴速度。
%
% 输入：
%   t         当前仿真时间，单位 s。
%   x         4x1 状态向量。
%   p         参数结构体。
%   forceFcn  外部力函数句柄，格式为 forceFcn(t,x,p)，输出 [Fx; Fy]。
%
% 输出：
%   dx        4x1 状态导数向量。
%
% 示例：
%   forceFcn = @(t,x,p) [0;0];
%   dx = HRG_WA_fast_rhs(t, x, p, forceFcn);

% -------------------------------------------------------------------------
% 1. 若没有提供外部力函数，则默认无外部驱动力
% -------------------------------------------------------------------------
if nargin < 4 || isempty(forceFcn)
    forceFcn = @(t,x,p) [0;0];
end

% -------------------------------------------------------------------------
% 2. 读取位移、速度和输入角速度
% -------------------------------------------------------------------------
r = x(1:2);                 % 位移向量 r = [X; Y]。
v = x(3:4);                 % 速度向量 v = [Xdot; Ydot]。
Omega = p.inputOmegaFcn(t); % 输入角速度，单位 rad/s。

% 反对称矩阵 J 用于表示科里奥利耦合项。
% J*v = [-Ydot; Xdot]。
J = [0 -1; 1 0];
I = eye(2);

% -------------------------------------------------------------------------
% 3. 定义各向异性矩阵 C(beta)
% -------------------------------------------------------------------------
% C(beta) 用于把阻尼不均匀和频率裂解从其主轴坐标旋转到 X/Y 坐标。
% 对二阶四波腹模态，物理轴角在矩阵中表现为 4*thetaAxis。
C = @(beta) [cos(beta) sin(beta); sin(beta) -cos(beta)];

% -------------------------------------------------------------------------
% 4. 构造阻尼矩阵和刚度矩阵
% -------------------------------------------------------------------------
% Dmat：平均阻尼 + 阻尼不均匀。
Dmat = 2*p.dampMean*I + p.err.dTauInv*C(4*p.err.thetaTau);

% Kmat：平均刚度 + 频率裂解。
% p.w0^2 为主刚度项；2*w0*dOmega 是小频率差的一阶近似。
Kmat = p.w0^2*I + 2*p.w0*p.err.dOmega*C(4*p.err.thetaOmega);

% -------------------------------------------------------------------------
% 5. 计算外部驱动力
% -------------------------------------------------------------------------
% forceFcn 可用于接入静电驱动、电压-力转换、控制力分配或外部扰动。
f = forceFcn(t,x,p);

% -------------------------------------------------------------------------
% 6. 二自由度谐振子加速度方程
% -------------------------------------------------------------------------
% a = -D*v - K*r + 2*cBryan*Omega*J*v + f
% 其中 2*cBryan*Omega*J*v 为输入角速度引起的科里奥利/进动耦合项。
a = -Dmat*v - Kmat*r + 2*p.cBryan*Omega*J*v + f(:);

% -------------------------------------------------------------------------
% 7. 组装状态导数
% -------------------------------------------------------------------------
% dx = [Xdot; Ydot; Xddot; Yddot]
dx = [v; a];
end
