function p=pcn_config()
% 参数入口：全部为合成表头参数，不是实测或厂家额定值。
% f0为Hz；gamma_intrinsic为1/s；Cs/Cf为F；G0为S；Rs/Rf为Ω。
% B为Bryan系数，Omega为输入机体角速度rad/s；theta0为初始模态方向rad。
% Ts为载波采样周期，Tc为解调周期；Tc/Ts必须是整数。
% charge_target为目标运动电荷C；vmax为合成限幅V。
% 驱动/检测矩阵为2×2，含两通道不一致与交叉耦合。
% virtual_rate为附加模态进动率；实际启用取决于建幅门控。
% All numeric head/limit values are synthetic bench assumptions.
% 【中文步骤】物理端口与合成标识；所有实测替换应保留单位和边界。
p=struct('schema','v10.1','synthetic',true,'f0',1000,'gamma_intrinsic',pi*1000/1e4,...
 'Cs',1e-9,'G0',1e-10,'kappa',1e-6,'b',1.1e-6,'Cds',0,'Rs',1000,...
 'B',.27699096196168066,'Omega',.5,'Ts',1/40000,'Tc',.001,'duration',.8,...
 'charge_target',1e-11,'initial_fraction',.3,'theta0',.4,...
 'Cf',100e-12,'Rf',1e9,'driver_tau',[20e-6;24e-6],'afe_bw',[20000;18000],...
 'detect_matrix',[1 .025;-.015 1.04],'drive_matrix',[1 -.03;.02 1.08],...
 'split_hz',0,'stiffness_axis',.37,'damping_half_difference',0,'damping_axis',-.23,...
 'adc_span',2,'adc_bits',20,'dac_span',2,'dac_bits',18,'vmax',1,...
 'agc_bw',5,'quad_bw',4,'pll_gain',30,'max_detune',30,'virtual_rate',0,...
 'virtual_start_min_s',.25,'virtual_settle_fraction',.01,'predict_heading',true,'max_heading_rate',100,'virtual_validated_limit',.2,...
 'min_amplitude_fraction',.02,'min_linearity',.1,'max_calibration_condition',100,...
 'max_frame_age',.002,'calibrate_detection',true,'calibrate_drive',true,...
 'noise_rms_V',0,'noise_seed',20261030);
assert(abs(p.Tc/p.Ts-round(p.Tc/p.Ts))<1e-10);
end
