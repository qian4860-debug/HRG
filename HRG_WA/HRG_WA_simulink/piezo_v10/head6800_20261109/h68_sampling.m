function report=h68_sampling
% Explicit bounds, with design assumptions separated from supplied values.
c=h68_config; fhi=c.p.f0+c.p.split_hz/2;
report=struct('head',c.head,'carrier_only_strict_lower_Hz',2*fhi, ...
 'assumed_envelope_bandwidth_Hz',100,'with_assumed_sideband_strict_lower_Hz',2*(fhi+100), ...
 'AD9215_min_typical_clock_Hz',5e6,'AD9215_pipeline_cycles',5, ...
 'AD9707_minimum_clock','No fixed minimum with DC-coupled clock (ADI support); observe board coupling and calibration', ...
 'AD9707_settling_0p1_percent_typical_s',11e-9,'modes',[]);
for mode={'continuous','tdm_shared'}
 c=h68_config(mode{1});fs=1/c.Ts;
 v=struct('mode',mode{1},'fs_ADC_Hz',fs,'fs_DAC_Hz',fs,'samples_per_carrier',c.n, ...
  'frame_rate_Hz',fs/c.frame,'valid_samples',c.n,'valid_window_s',c.n/fs, ...
  'drive_window_s',c.driveEnd/fs,'bleed_s',max(0,c.senseStart-c.driveEnd)/fs, ...
  'settle_s',(c.validStart-c.senseStart)/fs,'tail_s',(c.frame-c.validEnd)/fs, ...
  'DAC_ZOH_carrier_droop_fraction',1-sin(pi*c.p.carrier_hz/fs)/(pi*c.p.carrier_hz/fs), ...
  'analog_AAF_at_Nyquist_dB',-20*c.p.aaf_order*log10(sqrt(1+(fs/2/c.p.afe_bw(1))^2)), ...
  'assumed_16_valid_samples_lower_Hz',16/(c.n/fs));
 report.modes=[report.modes;v];
end
% A sample-rate increase does not repair a short aperture's IQ conditioning.
report.window_comparison=[];
for duration=[1/6800,55e-6,10e-6]
 fs=5440000; t=(0:ceil(duration*fs-1e-9)-1)'/fs;
 X=[cos(2*pi*6800*t),sin(2*pi*6800*t),ones(size(t))];
 report.window_comparison=[report.window_comparison; struct('window_s',duration,'samples',numel(t), ...
    'condition_with_unknown_DC',cond(X),'worst_normalized_variance',max(eig((X'*X)\eye(3))))];
end
here=fileparts(mfilename('fullpath'));fid=fopen(fullfile(here,'sampling.json'),'w','n','UTF-8');
fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
