function reg = HRG_WA_regmap(p)
% HRG_WA_REGMAP  Behavioral register map for FPGA/ASIC digital interface.
%
% 功能说明：
%   该函数给出半球陀螺 ASIC 数字控制接口电路建议寄存器表。它用于系统仿真、
%   FPGA 原型联调和后续 ASIC 软件驱动定义。寄存器地址和字段可在 RTL 设计时沿用。
%
% 输出：
%   reg  结构体数组，每个元素包含 addr/name/access/reset/desc。

if nargin < 1
    p = HRG_WA_params();
end

reg = struct('addr',{},'name',{},'access',{},'reset',{},'desc',{});
add = @(addr,name,access,reset,desc) struct('addr',addr,'name',name, ...
    'access',access,'reset',reset,'desc',desc);

reg(end+1) = add(hex2dec('0000'),'CTRL','RW',uint32(0), ...
    'bit0 global_enable, bit1 E_loop_en, bit2 Q_loop_en, bit3 virtual_rate_en, bit4 selftest_en');
reg(end+1) = add(hex2dec('0004'),'MODE','RW',uint32(p.reg.mode), ...
    '0 IDLE, 1 STARTUP, 2 LOCK, 3 RUN, 4 SELFTEST, 5 FAULT');
reg(end+1) = add(hex2dec('0008'),'STATUS','RO',uint32(0), ...
    'bit0 data_ready, bit1 lock, bit2 adc_sat, bit3 dac_sat, bit4 E_fault, bit5 Q_fault, bit6 angle_jump');
reg(end+1) = add(hex2dec('000C'),'IRQ_EN','RW',uint32(p.reg.int_enable), ...
    'interrupt enable mask');
reg(end+1) = add(hex2dec('0010'),'FAULT_CLEAR','WO',uint32(0), ...
    'write 1 to clear latched fault flags');
reg(end+1) = add(hex2dec('0020'),'KP_E','RW',single(p.ctrl.KpE), ...
    'energy loop proportional gain');
reg(end+1) = add(hex2dec('0024'),'KI_E','RW',single(p.ctrl.KiE), ...
    'energy loop integral gain');
reg(end+1) = add(hex2dec('0028'),'KP_Q','RW',single(p.ctrl.KpQ), ...
    'quadrature loop proportional gain');
reg(end+1) = add(hex2dec('002C'),'KI_Q','RW',single(p.ctrl.KiQ), ...
    'quadrature loop integral gain');
reg(end+1) = add(hex2dec('0030'),'FA_LIMIT','RW',single(p.ctrl.faLimit), ...
    'energy control saturation limit');
reg(end+1) = add(hex2dec('0034'),'FQ_LIMIT','RW',single(p.ctrl.fqLimit), ...
    'quadrature control saturation limit');
reg(end+1) = add(hex2dec('0040'),'ADC_CFG','RW',uint32(p.adc.bits), ...
    'ADC bit width and full-scale configuration');
reg(end+1) = add(hex2dec('0044'),'DAC_CFG','RW',uint32(p.dac.bits), ...
    'DAC bit width and full-scale configuration');
reg(end+1) = add(hex2dec('0050'),'CORDIC_CFG','RW',uint32(p.cordic.angleBits), ...
    'CORDIC angle output bit width and latency');
reg(end+1) = add(hex2dec('0060'),'CAL_E_GAIN','RW',single(p.cal.Egain), ...
    'digital calibration gain for E channel');
reg(end+1) = add(hex2dec('0064'),'CAL_Q_GAIN','RW',single(p.cal.Qgain), ...
    'digital calibration gain for Q channel');
reg(end+1) = add(hex2dec('0068'),'CAL_S_GAIN','RW',single(p.cal.Sgain), ...
    'digital calibration gain for S channel');
reg(end+1) = add(hex2dec('006C'),'CAL_R_GAIN','RW',single(p.cal.Rgain), ...
    'digital calibration gain for R channel');
reg(end+1) = add(hex2dec('0070'),'CAL_BIAS_RATE','RW',single(p.cal.biasRate), ...
    'output rate bias compensation');
reg(end+1) = add(hex2dec('0080'),'ANGLE_OUT_L','RO',uint32(0), ...
    'lower word of integrated angle output');
reg(end+1) = add(hex2dec('0084'),'ANGLE_OUT_H','RO',uint32(0), ...
    'upper word of integrated angle output when 64-bit output is used');
reg(end+1) = add(hex2dec('0088'),'RATE_OUT','RO',uint32(0), ...
    'rate output word');
reg(end+1) = add(hex2dec('008C'),'E_OUT','RO',uint32(0), ...
    'measured energy variable');
reg(end+1) = add(hex2dec('0090'),'Q_OUT','RO',uint32(0), ...
    'measured quadrature variable');
reg(end+1) = add(hex2dec('00A0'),'SAT_COUNT','RO',uint32(0), ...
    'combined ADC/DAC/fixed-point saturation counter');
reg(end+1) = add(hex2dec('00A4'),'SAMPLE_COUNT','RO',uint32(0), ...
    'control sample counter');
end
