 'adc_span',2,'adc_bits',20,'dac_span',2,'dac_bits',18,'vmax',1,...
 'agc_bw',5,'quad_bw',4,'pll_gain',30,'max_detune',30,'gain_y',1,...
 'calibrate',true,'synthetic',true);
% Everything after the fitted electrical fields is an explicit synthetic bench
% setting, not a measured head rating. A real-use release path is not supplied.
end
